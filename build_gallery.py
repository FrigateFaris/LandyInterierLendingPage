"""Convert every project photo from the Telegram download into site media (duplicates dropped).

-> media/p/<project>/NNN.webp (<=2200px) and media/p/<project>/t/NNN.webp (<=640px)
-> js/gallery-data.js  window.GALLERY = { <project>: [ {f, w, h, ch}, ... ] }
"""
import os, glob, json, re
from PIL import Image, ImageOps

SRC = r'C:\Users\Asus\Downloads\Telegram Desktop\Проекты интерьера'
ROOT = os.path.dirname(os.path.abspath(__file__))
# project id -> [(chapter title, folder)]
PROJECTS = {
    'house': [('', 'Частный дом (1 этаж)')],
    'hotel': [('Ресепшен и общие зоны', r'Отель\Ресепшен и общие зоны'), ('Номер 24', r'Отель\Номер Room24'),
              ('Номер 34', r'Отель\Номер Room34'), ('Санузел', r'Отель\Санузел SU001')],
    'graphite': [('', 'Квартира «Графит» (тёмная)')],
    'neoclassic': [('', 'Квартира «Неоклассика» (фото объекта)')],
    'wokebowl': [('', 'Кафе Wokebowl')],
    # loose renders in the Telegram root, picked by file-name masks
    'terrace': [('Прихожая', r'..\AllFIN001_*'), ('Гостиная', r'..\LVFIN001_*'), ('Спальня', r'..\MBFIN001_*'),
                ('Санузел спальни', r'..\MBSUFIN001_*'), ('Детская', r'..\NKidsFIN001_*'), ('Санузел детской', r'..\NKidSSUFIN001_*'),
                ('Гардеробная', r'..\WRDFIN001_*'), ('Постирочная', r'..\SUPrachkaFIN001_*'), ('Терраса', r'..\ZTerrasseFIN001_*')],
    'grey': [('', r'..\[0-9]*0000.jpg')],
    # stills taken from the house video by build_videos.py
    'greek': [('', os.path.join(ROOT, 'media', 'greek-stills', '*.jpg'))],
}

def ahash(im):
    g = ImageOps.grayscale(im).resize((16, 16), Image.BILINEAR)
    px = list(g.getdata()); m = sum(px) / len(px)
    return [p > m for p in px]

def rank(path):   # which copy of a duplicate to keep: edited > plain > "(2)" copies
    n = os.path.basename(path)
    return (0 if 'Edit' in n else 1, 1 if '(2)' in n else 0, -os.path.getsize(path))

data = {}
for pid, chapters in PROJECTS.items():
    out = os.path.join(ROOT, 'media', 'p', pid); os.makedirs(os.path.join(out, 't'), exist_ok=True)
    items, n = [], 0
    for ch, folder in chapters:
        pattern = folder if '*' in folder else os.path.join(folder, '*')
        files = sorted(f for f in glob.glob(os.path.join(SRC, pattern)) if re.search(r'\.(jpe?g|png|webp)$', f, re.I))
        # copies of one shot share a base name: "X (2).jpg", "X-Edit.jpg", "X-Edit-2.jpg" -> keep the best one
        base = lambda f: re.sub(r'(-Edit)?(-\d)?( \(\d\))?$', '', os.path.splitext(os.path.basename(f))[0])
        best = {}
        for f in sorted(files, key=rank): best.setdefault(base(f), f)
        kept = []   # (hash, path)
        for f in sorted(best.values(), key=rank):
            im = Image.open(f); im = ImageOps.exif_transpose(im).convert('RGB')
            h = ahash(im)
            if any(sum(a != b for a, b in zip(h, k)) <= 12 for k, _ in kept): continue
            kept.append((h, f))
        kept.sort(key=lambda x: os.path.basename(x[1]))
        for _, f in kept:
            n += 1
            im = ImageOps.exif_transpose(Image.open(f)).convert('RGB')
            big = im.copy(); big.thumbnail((2200, 2200), Image.LANCZOS); big.save(os.path.join(out, f'{n:03d}.webp'), quality=80)
            sm = im.copy(); sm.thumbnail((640, 640), Image.LANCZOS); sm.save(os.path.join(out, 't', f'{n:03d}.webp'), quality=72)
            items.append({'f': f'{n:03d}', 'w': big.width, 'h': big.height, 'ch': ch})
        print(pid, ch or '-', len(files), '->', len(kept))
    data[pid] = items

with open(os.path.join(ROOT, 'js', 'gallery-data.js'), 'w', encoding='utf-8', newline='') as fh:
    fh.write('/* generated by build_gallery.py: every project photo (duplicates dropped) */\nwindow.GALLERY = ' + json.dumps(data, ensure_ascii=False) + ';\n')
print({k: len(v) for k, v in data.items()})
