"""Glue the hero frames into a few "pack" files so a hosted page downloads 8 files instead of hundreds.

-> media/apartment/pack/<set>-N.bin   frames concatenated in loading order (coarse to fine: every 16th, 8th, ...)
-> js/frame-packs.js                  window.FRAME_PACKS = { <dir>: { total, packs: [{ file, bytes, frames: [[index, offset, length], ...] }] } }
Run after tools/rebuild_frames.py.
"""
import os, json, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APT = os.path.join(ROOT, 'media', 'apartment')
SETS = [('frames', 'media/apartment/frames/', 8), ('frames-m', 'media/apartment/frames-m/', 6)]

def load_order(n):
    seen, order = [False] * n, []
    for step in (16, 8, 4, 2, 1):
        for i in range(0, n, step):
            if not seen[i]: seen[i] = True; order.append(i)
    return order

out_dir = os.path.join(APT, 'pack'); os.makedirs(out_dir, exist_ok=True)
for f in glob.glob(os.path.join(out_dir, '*.bin')): os.remove(f)
index = {}
for name, key, n_packs in SETS:
    files = sorted(glob.glob(os.path.join(APT, name, 'f*.webp')))
    n = len(files); order = load_order(n)
    per = -(-n // n_packs)
    packs, total = [], 0
    for p in range(n_packs):
        chunk = order[p * per:(p + 1) * per]
        if not chunk: break
        fname = f'{name}-{p}.bin'; frames, off = [], 0
        with open(os.path.join(out_dir, fname), 'wb') as out:
            for i in chunk:
                data = open(files[i], 'rb').read(); out.write(data)
                frames.append([i, off, len(data)]); off += len(data)
        packs.append({'file': 'media/apartment/pack/' + fname, 'bytes': off, 'frames': frames}); total += off
    index[key] = {'total': total, 'packs': packs}
    print(name, n, 'frames ->', len(packs), 'packs,', round(total / 1e6, 1), 'MB')

with open(os.path.join(ROOT, 'js', 'frame-packs.js'), 'w', encoding='utf-8', newline='') as fh:
    fh.write('/* generated by tools/pack_frames.py: hero frames glued into a few files (used when the page is served over http) */\n')
    fh.write('window.FRAME_PACKS = ' + json.dumps(index, separators=(',', ':')) + ';\n')
